#!/usr/bin/env python3
"""Bind Compose to a locally verified receiver image without starting services."""

import argparse
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
if __package__ in (None, ''):
    sys.path.insert(0, str(ROOT))

from scripts.prepare_release_candidate import verify_bundle


SERVICES = ('shirasu', 'metrics', 'backup')
IMAGE_ID = re.compile(r'sha256:[0-9a-f]{64}')
HASH = re.compile(r'[0-9a-f]{64}')

# Run only inside a disposable, read-only container, without mounts or network.
# Do not import the application (which could load a deployment's configuration).
VERIFY_IMAGE = '''import hashlib, json, pathlib, sys
expected = json.load(sys.stdin)
root = pathlib.Path('/app')
actual = {}
for path in root.rglob('*'):
    if path.is_symlink() or not path.is_file():
        raise SystemExit('Receiver image contains unexpected entries')
    name = path.relative_to(root).as_posix()
    if name not in expected:
        raise SystemExit('Receiver image contains unexpected files')
    actual[name] = hashlib.sha256(path.read_bytes()).hexdigest()
if actual != expected:
    raise SystemExit('Receiver image differs from the candidate')
print(json.dumps({'verified_files': len(actual)}))
'''


def _docker(arguments, *, input=None):
    result = subprocess.run(['docker', *arguments], input=input, capture_output=True,
                            text=True, timeout=120, check=False)
    if result.returncode:
        # Never dump image configuration, arbitrary container output or secrets.
        raise ValueError('Docker ' + arguments[0] + ' failed; check the local image and Docker access')
    return result.stdout


def inspect_image(image):
    if (not isinstance(image, str) or len(image) > 512
            or re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.:/@-]*', image) is None):
        raise ValueError('Expected a local Docker image reference')
    fields = ('WorkingDir', 'Cmd', 'Entrypoint', 'User', 'Volumes')
    # Docker can omit unset optional Config keys instead of returning null.
    template = '{{json .Id}}\n' + '\n'.join(
        '{{json (index .Config "' + field + '")}}' for field in fields)
    try:
        values = [json.loads(line) for line in _docker(
            ['image', 'inspect', '--format', template, image]).splitlines()]
        image_id, workdir, command, entrypoint, user, volumes = values
    except (json.JSONDecodeError, ValueError) as error:
        raise ValueError('Cannot inspect the local receiver image') from error
    if not isinstance(image_id, str) or IMAGE_ID.fullmatch(image_id) is None:
        raise ValueError('Docker did not return a full image ID')
    if (workdir != '/app' or command != ['python', './main.py']
            or entrypoint not in (None, []) or user not in (None, '', 'root', '0')
            or volumes not in (None, {})):
        raise ValueError('Receiver image startup configuration differs from the candidate Dockerfile')
    return image_id


def render_override(image_id, manifest_sha256):
    if not isinstance(image_id, str) or IMAGE_ID.fullmatch(image_id) is None:
        raise ValueError('A full sha256 Docker image ID is required')
    if not isinstance(manifest_sha256, str) or HASH.fullmatch(manifest_sha256) is None:
        raise ValueError('A candidate manifest SHA-256 is required')
    lines = [
        '# Generated by scripts/prepare_release_compose.py; contains no credentials.',
        '# Merge AFTER compose.yaml and all existing host overrides.',
        '# Keep this file in COMPOSE_FILE for subsequent operational commands.',
        'x-shirasu-release:',
        '  bundle-manifest-sha256: "' + manifest_sha256 + '"',
        'services:',
    ]
    for service in SERVICES:
        lines += ['  ' + service + ':', '    build: !reset null',
                  '    image: "' + image_id + '"', '    pull_policy: never']
    return '\n'.join(lines) + '\n'


def prepare(bundle, image, output):
    bundle, output = Path(bundle).absolute(), Path(output).absolute()
    if output.resolve().is_relative_to(bundle.resolve()):
        raise ValueError('Write the Compose override outside the fixed candidate')
    if output.exists() or output.is_symlink():
        raise FileExistsError('Compose override already exists: ' + str(output))
    manifest = verify_bundle(bundle)
    image_id = inspect_image(image)
    expected = {name.removeprefix('receiver/'): digest
                for name, digest in manifest['files'].items() if name.startswith('receiver/')}
    result = json.loads(_docker(
        ['run', '--rm', '--pull', 'never', '--network', 'none', '--read-only',
         '--cap-drop', 'ALL', '--security-opt', 'no-new-privileges',
         '--entrypoint', 'python', '-i', image_id, '-B', '-c', VERIFY_IMAGE],
        input=json.dumps(expected)))
    if result != {'verified_files': len(expected)}:
        raise ValueError('Receiver image file verification did not complete')
    if verify_bundle(bundle) != manifest:
        raise ValueError('Candidate changed during image verification')
    override = render_override(image_id, manifest['manifest_sha256'])
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open('x', encoding='utf-8') as stream:
        stream.write(override)
    return {'bundle_manifest_sha256': manifest['manifest_sha256'],
            'image_id': image_id, 'compose_file': str(output)}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bundle', type=Path, required=True)
    parser.add_argument('--image', required=True, help='existing local candidate receiver image tag or ID')
    parser.add_argument('--output', type=Path, required=True, help='new Compose override, outside the candidate')
    args = parser.parse_args(argv)
    try:
        result = prepare(args.bundle, args.image, args.output)
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print('Release Compose preparation failed: ' + str(error), file=sys.stderr)
        return 1
    print(json.dumps(result, sort_keys=True))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
